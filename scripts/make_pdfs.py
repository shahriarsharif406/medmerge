import html, pathlib, subprocess, sys
root = pathlib.Path(__file__).resolve().parent.parent
chrome = '/usr/bin/google-chrome'
def pdf(src, dst):
    subprocess.run([chrome, '--headless', '--no-sandbox', '--disable-gpu', '--no-pdf-header-footer', f'--print-to-pdf={dst}', f'file://{src}'], check=True, capture_output=True)
pdf(root/'docs/onepager.html', root/'docs/MedMerge-one-page.pdf')
files = ['index.html','style.css','app.js','engine.js','scripts/build_data.py','tests/engine.test.mjs','README.md']
parts = ['<meta charset="utf-8"><style>@page{margin:12mm}body{font:8pt/1.3 monospace}h2{font:700 11pt sans-serif;border-bottom:1px solid #000;margin:14px 0 4px;page-break-before:auto}pre{white-space:pre-wrap;word-break:break-all;margin:0}</style><h1 style="font:700 16pt sans-serif">MedMerge — source code</h1><p>Repo: github.com/shahriarsharif406/medmerge. data/medmerge-data.json (1.6 MB, generated by scripts/build_data.py) and data/samples.json omitted from this listing.</p>']
for f in files:
    parts.append(f'<h2>{f}</h2><pre>{html.escape((root/f).read_text())}</pre>')
(root/'docs/code.html').write_text(''.join(parts))
pdf(root/'docs/code.html', root/'docs/MedMerge-code.pdf')
(root/'docs/code.html').unlink()
